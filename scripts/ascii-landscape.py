"""Turn one of Pedro's landscape photos into the ASCII landscape of the footer.

Usage (from web/):
    python scripts/ascii-landscape.py public/images/hero.JPG
    python scripts/ascii-landscape.py <photo> --top 0.35 --bottom 0.95

Writes lib/footer-ascii.ts with two versions (desktop and mobile). Dark areas
become dense characters and bright areas become blank, so on the paper
background the sky dissolves into the page, like an engraving.

Options:
    --top / --bottom   vertical crop of the photo (0-1) before resizing
    --sky              brightness above which a cell is left blank (0-1)
    --gamma            >1 darkens mid-tones (more texture in the land)
"""
import argparse
import math
from pathlib import Path

from PIL import Image, ImageOps, ImageEnhance

# Light to dark. The first char must be a space (blank paper).
RAMP = " .,:;-~=+*xoX#"
# Monospace cells are taller than they are wide: width / height of a cell
# with line-height 1 in Geist Mono.
CELL_ASPECT = 0.6

VERSIONS = {
    "desktop": {"cols": 180, "aspect": 3.4},  # very wide strip
    "mobile": {"cols": 84, "aspect": 2.0},    # taller crop for phones
}


def to_ascii(img: Image.Image, cols: int, aspect: float, sky: float, gamma: float,
             dither: bool = True, edges: float = 0.0) -> str:
    w, h = img.size
    # Crop to the target aspect, keeping the bottom (the land) and centre.
    target_h = min(h, round(w / aspect))
    target_w = min(w, round(target_h * aspect))
    left = (w - target_w) // 2
    top = h - target_h
    img = img.crop((left, top, left + target_w, top + target_h))

    rows = max(1, round(cols / aspect * CELL_ASPECT))
    small = img.resize((cols, rows), Image.LANCZOS)
    lum = [[small.getpixel((x, y)) / 255 for x in range(cols)] for y in range(rows)]

    # Darkness 0..1 per cell (0 = blank paper), after the sky threshold and gamma.
    dark = [[0.0 if v >= sky else (1 - v / sky) ** (1 / gamma) for v in row] for row in lum]

    levels = len(RAMP) - 1
    out = [[" "] * cols for _ in range(rows)]
    for y in range(rows):
        for x in range(cols):
            d = dark[y][x]
            q = round(d * levels)
            out[y][x] = RAMP[q]
            if dither:
                # Floyd-Steinberg: spread the rounding error to the neighbours, so
                # tones become texture instead of flat bands.
                err = d - q / levels
                for dx, dy, wgt in ((1, 0, 7), (-1, 1, 3), (0, 1, 5), (1, 1, 1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < cols and ny < rows and dark[ny][nx] > 0:
                        dark[ny][nx] = min(1.0, max(0.0, dark[ny][nx] + err * wgt / 16))

    if edges > 0:
        # Sobel on the luminance: strong edges are drawn with a character that
        # follows the direction of the contour, like an engraved outline.
        for y in range(1, rows - 1):
            for x in range(1, cols - 1):
                L = lambda dx, dy: lum[y + dy][x + dx]
                gx = (L(1, -1) + 2 * L(1, 0) + L(1, 1)) - (L(-1, -1) + 2 * L(-1, 0) + L(-1, 1))
                gy = (L(-1, 1) + 2 * L(0, 1) + L(1, 1)) - (L(-1, -1) + 2 * L(0, -1) + L(1, -1))
                mag = (gx * gx + gy * gy) ** 0.5
                if mag < edges:
                    continue
                angle = math.degrees(math.atan2(gy, gx)) % 180   # gradient direction
                # The contour runs perpendicular to the gradient.
                if angle < 22.5 or angle >= 157.5:
                    ch = "|"
                elif angle < 67.5:
                    ch = "\\"
                elif angle < 112.5:
                    ch = "_"
                else:
                    ch = "/"
                out[y][x] = ch

    return "\n".join("".join(row).rstrip() for row in out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("photo")
    ap.add_argument("--top", type=float, default=0.0)
    ap.add_argument("--bottom", type=float, default=1.0)
    ap.add_argument("--sky", type=float, default=0.62)
    ap.add_argument("--gamma", type=float, default=1.25)
    ap.add_argument("--no-dither", action="store_true", help="flat tone bands instead of error diffusion")
    ap.add_argument("--edges", type=float, default=1.4, help="Sobel threshold for contour characters (0 = off)")
    ap.add_argument("--out", default="lib/footer-ascii.ts")
    a = ap.parse_args()

    img = ImageOps.exif_transpose(Image.open(a.photo)).convert("L")
    w, h = img.size
    img = img.crop((0, round(h * a.top), w, round(h * a.bottom)))
    img = ImageOps.autocontrast(img, cutoff=1)
    img = ImageEnhance.Contrast(img).enhance(1.15)

    out = [
        "// Generated by scripts/ascii-landscape.py. Do not edit by hand.",
        f"// Source: {Path(a.photo).name} (top={a.top}, bottom={a.bottom}, sky={a.sky}, gamma={a.gamma}, edges={a.edges}, dither={not a.no_dither})",
        "",
    ]
    for name, v in VERSIONS.items():
        art = to_ascii(img, v["cols"], v["aspect"], a.sky, a.gamma, not a.no_dither, a.edges)
        # Pad every line to the full width so the block keeps its width when trimmed.
        art = "\n".join(line.ljust(v["cols"]) for line in art.split("\n"))
        escaped = art.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
        out.append(f"export const ASCII_{name.upper()}_COLS = {v['cols']};")
        out.append(f"export const ASCII_{name.upper()} = `{escaped}`;")
        out.append("")
    Path(a.out).write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
